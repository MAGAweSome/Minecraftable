/**
 * Draws a POI marker icon at the given screen coordinates.
 * - Draws a solid icon with a crisp 1px white border.
 * - Renders at ~35% opacity if marked as completed.
 * - Highlights on hover.
 */
export function drawPoiMarker(ctx, spriteKey, screenX, screenY, isCompleted = false, isHovered = false) {
  if (!mapPoiImage) return;
  const sprite = POI_SPRITES[spriteKey] || POI_SPRITES['bastion'];
  if (!sprite) return;

  const targetSize = 24;
  const half = targetSize / 2;
  const drawX = Math.round(screenX - half);
  const drawY = Math.round(screenY - half);

  ctx.save();
  
  // Translucency for completed structures (~35% opacity)
  if (isCompleted) {
    ctx.globalAlpha = 0.35;
  } else {
    ctx.globalAlpha = 1.0;
  }

  // Draw background frame (1.5px white border box matching Chunkbase)
  ctx.fillStyle = 'rgba(255, 255, 255, 0.9)';
  ctx.strokeStyle = isHovered ? '#1f6feb' : 'rgba(255, 255, 255, 0.95)';
  ctx.lineWidth = isHovered ? 2 : 1.5;
  
  // Outer rectangle with slight corner rounding
  const r = 2;
  ctx.beginPath();
  ctx.roundRect(drawX - 2, drawY - 2, targetSize + 4, targetSize + 4, r);
  ctx.fill();
  ctx.stroke();

  // Draw the sprite from seed-map-pois.webp
  ctx.drawImage(
    mapPoiImage,
    sprite.x, sprite.y, sprite.width, sprite.height,
    drawX, drawY, targetSize, targetSize
  );

  ctx.restore();
}
