let mapPoiImage = null;
let panelIconsImage = null;
let imagesLoaded = false;

export function loadPoiImages() {
  if (imagesLoaded && mapPoiImage) return Promise.resolve({ mapPoiImage, panelIconsImage });
  
  return Promise.all([
    new Promise((resolve) => {
      const img = new Image();
      img.src = '/seed-map-pois.webp';
      img.onload = () => { mapPoiImage = img; resolve(img); };
      img.onerror = () => { console.warn('Failed to load seed-map-pois.webp'); resolve(null); };
    }),
    new Promise((resolve) => {
      const img = new Image();
      img.src = '/chunk-finders-tn.webp';
      img.onload = () => { panelIconsImage = img; resolve(img); };
      img.onerror = () => { console.warn('Failed to load chunk-finders-tn.webp'); resolve(null); };
    })
  ]).then(() => {
    imagesLoaded = true;
    return { mapPoiImage, panelIconsImage };
  });
}

